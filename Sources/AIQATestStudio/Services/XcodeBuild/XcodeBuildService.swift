import Foundation

struct XcodeContainer: Hashable, Identifiable, Sendable {
    enum Kind: String, Sendable { case workspace, project }
    let kind: Kind
    let url: URL

    var id: String { url.path }
    var name: String { url.deletingPathExtension().lastPathComponent }
    var flag: String { kind == .workspace ? "-workspace" : "-project" }
    var displayName: String { "\(url.lastPathComponent) (\(kind.rawValue))" }
}

struct BuiltApp: Hashable, Sendable {
    let appURL: URL
    let bundleID: String
    let productName: String
    let targetName: String
}

struct AppTarget: Hashable, Sendable {
    let targetName: String
    let bundleID: String
}

/// Builds the selected project with xcodebuild. All arguments are generated by trusted code and passed as an
/// argv array (no shell).
final class XcodeBuildService {

    // MARK: Arguments

    static func destination(udid: String) -> String { "platform=iOS Simulator,id=\(udid)" }

    static func baseArguments(container: XcodeContainer, scheme: String, configuration: String) -> [String] {
        [container.flag, container.url.path, "-scheme", scheme, "-configuration", configuration] + packageArguments(for: container)
    }

    /// One shared Swift-package checkout per project: `-list`, `-showBuildSettings` and `build` all reuse it, so
    /// packages are fetched only the first time (and never re-resolved/updated afterwards).
    static func packageArguments(for container: XcodeContainer) -> [String] {
        let directory = AppPaths.derivedData(for: container.url.path).appendingPathComponent("SourcePackages", isDirectory: true)
        return ["-clonedSourcePackagesDirPath", directory.path, "-skipPackageUpdates"]
    }

    // MARK: Build

    /// Builds and returns the verified `.app` product. Throws on non-zero exit or when no valid artifact exists.
    func build(container: XcodeContainer, scheme: String, configuration: String, simulatorUDID: String,
               disableSigning: Bool, derivedData: URL,
               onLine: @escaping @Sendable (String) -> Void) async throws -> BuiltApp {
        var args = Self.baseArguments(container: container, scheme: scheme, configuration: configuration)
        args += ["-destination", Self.destination(udid: simulatorUDID), "-derivedDataPath", derivedData.path]
        // Never build fully unsigned: without a signature the app has no entitlements, so Keychain (login/session) fails.
        // Ad-hoc signing needs no Apple team and embeds the entitlements, like a Run from Xcode on the Simulator.
        if disableSigning { args += ["CODE_SIGN_IDENTITY=-", "CODE_SIGNING_REQUIRED=NO", "CODE_SIGNING_ALLOWED=YES", "CODE_SIGN_STYLE=Manual", "DEVELOPMENT_TEAM="] }
        // Leave headroom for the Simulator/Appium/Ollama: cap parallel compile jobs at half the cores.
        args += ["-jobs", String(max(2, ProcessInfo.processInfo.activeProcessorCount / 2)), "build"]

        onLine("$ xcodebuild " + args.map { $0.contains(" ") ? "\"\($0)\"" : $0 }.joined(separator: " "))
        let tail = TailBuffer(limit: 400)
        let result = try await ProcessRunner.run("/usr/bin/xcodebuild", args, collectOutput: false) { line in
            tail.add(line)
            onLine(line)
        }

        guard result.exitCode == 0 else {
            throw Self.failure(exitCode: result.exitCode, lines: tail.lines)
        }
        onLine("xcodebuild exited with status 0 — locating the built product…")
        let app = try await resolveProduct(container: container, scheme: scheme, configuration: configuration,
                                           simulatorUDID: simulatorUDID, derivedData: derivedData)
        onLine("Built app: \(app.appURL.path)  (bundle id \(app.bundleID))")
        return app
    }

    // MARK: Build settings → product

    private struct SettingsEntry: Decodable {
        let target: String?
        let buildSettings: [String: String]
    }

    private func buildSettings(container: XcodeContainer, scheme: String, configuration: String,
                               destination: String, derivedData: URL?) async throws -> [SettingsEntry] {
        var args = Self.baseArguments(container: container, scheme: scheme, configuration: configuration)
        args += ["-destination", destination]
        if let derivedData { args += ["-derivedDataPath", derivedData.path] }
        args += ["-showBuildSettings", "-json"]
        let result = try await ProcessRunner.run("/usr/bin/xcodebuild", args, mergeStderr: false)
        guard result.succeeded, let data = JSONExtract.payload(from: result.output),
              let entries = try? JSONDecoder().decode([SettingsEntry].self, from: data) else {
            throw AppError("Could not read build settings: \(result.errorOutput.tailLines(4))",
                           recovery: "Check the scheme is shared and its dependencies (Pods / Swift packages) are resolved.")
        }
        return entries
    }

    /// App targets and their bundle identifiers (before building) – used for display.
    func appTargets(container: XcodeContainer, scheme: String, configuration: String) async throws -> [AppTarget] {
        let entries = try await buildSettings(container: container, scheme: scheme, configuration: configuration,
                                              destination: "generic/platform=iOS Simulator", derivedData: nil)
        return entries.compactMap { entry in
            guard entry.buildSettings["WRAPPER_EXTENSION"] == "app",
                  let bundle = entry.buildSettings["PRODUCT_BUNDLE_IDENTIFIER"] else { return nil }
            return AppTarget(targetName: entry.target ?? entry.buildSettings["TARGET_NAME"] ?? "", bundleID: bundle)
        }
    }

    private func resolveProduct(container: XcodeContainer, scheme: String, configuration: String,
                                simulatorUDID: String, derivedData: URL) async throws -> BuiltApp {
        let entries = try await buildSettings(container: container, scheme: scheme, configuration: configuration,
                                              destination: Self.destination(udid: simulatorUDID), derivedData: derivedData)
        let candidates = entries.filter { $0.buildSettings["WRAPPER_EXTENSION"] == "app" }
        // Prefer the target named like the scheme, then any app product that exists on disk.
        let ordered = candidates.sorted { a, _ in (a.target ?? "") == scheme }
        for entry in ordered {
            let settings = entry.buildSettings
            guard let dir = settings["TARGET_BUILD_DIR"], let product = settings["FULL_PRODUCT_NAME"] else { continue }
            let appURL = URL(fileURLWithPath: dir).appendingPathComponent(product)
            guard FileManager.default.fileExists(atPath: appURL.path) else { continue }

            let plist = NSDictionary(contentsOf: appURL.appendingPathComponent("Info.plist"))
            guard let bundleID = plist?["CFBundleIdentifier"] as? String else { continue }
            let platform = (plist?["CFBundleSupportedPlatforms"] as? [String]) ?? []
            if !platform.isEmpty && !platform.contains("iPhoneSimulator") { continue }
            return BuiltApp(appURL: appURL, bundleID: bundleID, productName: product, targetName: entry.target ?? "")
        }
        throw AppError("The build finished but no installable iOS Simulator .app product was found for scheme “\(scheme)”.",
                       recovery: "Choose a scheme that builds an application target (not a framework or test bundle).")
    }

    // MARK: Failure analysis

    static func failure(exitCode: Int32, lines: [String]) -> AppError {
        let errors = lines.filter { $0.contains("error:") || $0.contains("fatal error") }
        var seen = Set<String>()
        let unique = errors.filter { seen.insert($0).inserted }.suffix(8)
        let summary = unique.isEmpty ? lines.suffix(8).joined(separator: "\n") : unique.joined(separator: "\n")
        let joined = lines.joined(separator: "\n")

        let recovery: String
        if joined.contains("No such module") && (joined.contains("Pods") || joined.contains("Pod")) {
            recovery = "CocoaPods dependencies look missing. In the project folder run `pod install`, then build again."
        } else if joined.contains("No such module") || joined.contains("Missing package product") || joined.contains("could not resolve package") || joined.localizedCaseInsensitiveContains("Package.resolved") {
            recovery = "Swift packages are not resolved. Run `xcodebuild -resolvePackageDependencies -project/-workspace …` or open the project in Xcode once."
        } else if joined.contains("requires a development team") || joined.contains("Signing for") || joined.contains("code signing") {
            recovery = "Signing failed. Keep “Disable code signing” enabled (Simulator builds don't need signing) or set a team in Xcode."
        } else if joined.contains("Unable to find a destination matching") || joined.contains("Unable to find a device matching") {
            recovery = "The selected Simulator/runtime isn't usable for this project. Pick another Simulator or install the runtime."
        } else if joined.contains("deployment target") {
            recovery = "The Simulator iOS version is lower than the app's deployment target. Choose a newer Simulator runtime."
        } else if joined.contains("does not contain a scheme") || joined.contains("not a shared scheme") {
            recovery = "Make the scheme shared: Xcode ▸ Product ▸ Scheme ▸ Manage Schemes ▸ tick “Shared”."
        } else {
            recovery = "Fix the compiler errors in the source project (this tool never edits your code) and rebuild. Full log is saved on disk."
        }
        return AppError("Build failed (exit code \(exitCode)).\n\(summary)", recovery: recovery)
    }

    /// Short human-readable description of the current xcodebuild step.
    static func operation(from line: String) -> String? {
        let steps = ["CompileSwiftSources", "CompileSwift", "SwiftCompile", "CompileC", "Ld ", "CodeSign", "ProcessInfoPlistFile",
                     "CopySwiftLibs", "ProcessProductPackaging", "GenerateDSYMFile", "CompileAssetCatalog", "CompileStoryboard",
                     "LinkStoryboards", "PhaseScriptExecution", "Resolve Package Graph", "SwiftEmitModule", "Touch ", "Copy ",
                     "CreateBuildDirectory", "SwiftDriver"]
        guard let step = steps.first(where: { line.hasPrefix($0) }) else {
            if line.hasPrefix("Build target ") { return line }
            return nil
        }
        let detail = line.split(separator: " ").dropFirst().first.map { URL(fileURLWithPath: String($0)).lastPathComponent } ?? ""
        return "\(step.trimmingCharacters(in: .whitespaces)) \(detail)".trimmingCharacters(in: .whitespaces)
    }
}

final class TailBuffer: @unchecked Sendable {
    private let lock = NSLock()
    private var storage: [String] = []
    private let limit: Int
    init(limit: Int) { self.limit = limit }
    func add(_ line: String) {
        lock.lock(); defer { lock.unlock() }
        storage.append(line)
        if storage.count > limit { storage.removeFirst(storage.count - limit) }
    }
    var lines: [String] { lock.lock(); defer { lock.unlock() }; return storage }
}
